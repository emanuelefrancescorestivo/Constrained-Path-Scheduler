"""
A semester, planned week by week (AUDIT.md item 33).

The owner's four-month timetable showed the defect: with each course as one memory
item that is already partly known, the plan finished every subject by late
November and left the two months before the January exams empty, although
lectures went on until December. This script reproduces that on a synthetic
timetable in the same format, `examples/sample-semester.ics` (six courses, a
lecture and a tutorial a week each from 28 September to 18 December, a holiday
week, one class cancelled in its title, exams from 25 to 29 January), and shows
what planning each week of lectures as a topic changes. The owner's calendar is
personal and is not in the repository; this one is generated by `--write`.

    python benchmarks/semester.py            # both models, the published numbers
    python benchmarks/semester.py --write    # regenerate the calendar file
    python benchmarks/semester.py --candidates 3 4 6   # the cap, measured

Every number is the modal plan (every review succeeds), one run: the planner is
deterministic, so there is no error bar to give; wall-clock times depend on the
machine and are there for scale only.
"""

from __future__ import annotations

import argparse
import sys
import time
from collections import Counter
from datetime import date, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from cps import rolling, service  # noqa: E402

CALENDAR = ROOT / "examples" / "sample-semester.ics"
START = date(2026, 9, 29)
TZ = "Europe/Paris"
FIRST_WEEK = date(2026, 9, 28)
LAST_WEEK = date(2026, 12, 14)
HOLIDAY = date(2026, 10, 26)  # no teaching that week

# Course, weekday of the lecture and of the tutorial, start hour, exam.
COURSES = (
    ("Computer Programming 3", 0, 2, 9, datetime(2027, 1, 25, 13, 45)),
    ("Algebra 3", 0, 3, 14, datetime(2027, 1, 26, 9, 0)),
    ("Advanced Statistics", 1, 3, 9, datetime(2027, 1, 27, 9, 0)),
    ("Analysis 3", 1, 4, 14, datetime(2027, 1, 28, 9, 0)),
    ("Ethics & Philosophy of AI", 2, 4, 16, datetime(2027, 1, 28, 15, 30)),
    ("Deep Learning 1", 2, 0, 9, datetime(2027, 1, 29, 13, 45)),
)


def _stamp(moment: datetime) -> str:
    return moment.strftime("%Y%m%dT%H%M%S")


def calendar_text() -> str:
    """The synthetic semester as an .ics, deterministic."""
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//constrained-path-scheduler//semester//EN"]

    def event(uid: str, begin: datetime, minutes: int, summary: str) -> None:
        lines.extend(
            [
                "BEGIN:VEVENT",
                f"UID:{uid}@example",
                f"DTSTART;TZID={TZ}:{_stamp(begin)}",
                f"DTEND;TZID={TZ}:{_stamp(begin + timedelta(minutes=minutes))}",
                f"SUMMARY:{summary}",
                "END:VEVENT",
            ]
        )

    for number, (course, lecture_day, tutorial_day, hour, exam) in enumerate(COURSES):
        monday = FIRST_WEEK
        while monday <= LAST_WEEK:
            if monday != HOLIDAY:
                for kind, weekday, offset in (("CM", lecture_day, 0), ("TD", tutorial_day, 2)):
                    day = monday + timedelta(days=weekday)
                    begin = datetime(day.year, day.month, day.day, hour + offset)
                    title = f"{course}, Grp: {kind} ., Salle: Salle {number + 1}"
                    # One lecture is cancelled in its title only, as the owner's export does.
                    if course == "Ethics & Philosophy of AI" and kind == "CM" and monday == date(2026, 12, 7):
                        title += ", COURS ANNULE"
                    event(f"{number}-{kind}-{monday:%Y%m%d}", begin, 90, title)
            monday += timedelta(days=7)
        event(f"{number}-exam", exam, 180, f"{course}, Grp: EXAMEN ., Salle: Amphi")
    monday = FIRST_WEEK
    while monday <= date(2027, 1, 25):
        thursday = monday + timedelta(days=3)
        event(f"gym-{monday:%Y%m%d}", datetime(thursday.year, thursday.month, thursday.day, 19), 90, "Gym")
        monday += timedelta(days=7)
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def run(report: service.CalendarReport, topics: bool, candidates: int | None = None) -> dict:
    specs = [service.SubjectSpec(a.subject, None, familiarity=3) for a in report.assessments]
    if candidates is not None:
        service.TOPIC_CANDIDATES = candidates
    rolling._SOLVED.clear()  # every run pays for its own value-function solves
    begin = time.perf_counter()
    plan = service.make_plan(report, specs, window=4, lectures_as_topics=topics)
    seconds = time.perf_counter() - begin
    weeks = Counter(int(s.start_day // 7) for s in plan.sessions)
    last_teaching = (LAST_WEEK + timedelta(days=5) - START).days
    return {
        "plan": plan,
        "seconds": seconds,
        "sessions": len(plan.sessions),
        "weeks": [weeks.get(w, 0) for w in range(max(weeks) + 1)] if weeks else [],
        "after_teaching": sum(1 for s in plan.sessions if s.start_day > last_teaching),
        "last_session": max((s.start[:10] for s in plan.sessions), default="none"),
        "topics": sum(s.topics for s in plan.subjects),
        "ready": sum(s.topics_ready if s.topics > 1 else int(s.ready) for s in plan.subjects),
        "recall": [round(s.recall_at_exam, 2) for s in plan.subjects],
    }


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--write", action="store_true", help="regenerate examples/sample-semester.ics")
    parser.add_argument("--candidates", type=int, nargs="*", help="compare topic caps instead")
    args = parser.parse_args()
    if args.write:
        CALENDAR.write_bytes(calendar_text().encode("utf-8"))
        print(f"wrote {CALENDAR.relative_to(ROOT)}")
        return 0
    text = CALENDAR.read_bytes()
    # Compared without line endings, which a git checkout may rewrite.
    if text.decode("utf-8").replace("\r\n", "\n") != calendar_text().replace("\r\n", "\n"):
        print("examples/sample-semester.ics differs from the generator; run with --write", file=sys.stderr)
        return 1
    report = service.analyse_calendar(text, start=START, tz=TZ, block_minutes=90, blocks_per_day=2)
    print(
        f"{len(report.assessments)} exams, {len(report.lectures)} other events, "
        f"{len(report.blocks)} free blocks of 90 minutes from {START} to the last exam"
    )
    if args.candidates:
        for cap in args.candidates:
            r = run(report, topics=True, candidates=cap)
            print(
                f"  at most {cap} topics a window: {r['ready']} of {r['topics']} topics at target, "
                f"{r['seconds']:.0f} s"
            )
        return 0
    for label, topics in (("each course one topic", False), ("a topic per week of lectures", True)):
        r = run(report, topics)
        print(f"\n{label}:")
        print(
            f"  sessions {r['sessions']}, last on {r['last_session']}, "
            f"{r['after_teaching']} after teaching ends"
        )
        print(f"  sessions per week: {' '.join(str(n) for n in r['weeks'])}")
        print(f"  {r['ready']} of {r['topics']} topics at target; recall at the exams {r['recall']}")
        short = [
            (s["name"], service._subject(s).target(0.9), final[s["name"]][0].stability)
            for final in [service._replay(r["plan"].specs, r["plan"].sessions)]
            for s in r["plan"].specs
            if final[s["name"]][0].stability < service._subject(s).target(0.9)
        ]
        for name, target, reached in short:
            print(f"  short of target: {name}, {reached:.0f} of {target:.0f} days")
        print(f"  planned in {r['seconds']:.0f} s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
